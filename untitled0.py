import math
import numpy as np
import matplotlib.pyplot as plt
from collections import Counter
from transformers import AutoTokenizer
from sacremoses import MosesTokenizer
from datasets import load_dataset
from tabulate import tabulate


# --- 1. HELPER FUNCTIONS ---

def get_ngrams(tokens, n):
    return [tuple(tokens[i:i + n]) for i in range(len(tokens) - n + 1)]


def split_data(data, train_size=700, heldout_size=200, test_size=100):
    """Splits the first 1000 documents into Train (700), Heldout (200), Test (100)."""
    texts = data['text']
    return (texts[:train_size],
            texts[train_size:train_size + heldout_size],
            texts[train_size + heldout_size:train_size + heldout_size + test_size])


def tokenize_batch(texts, tokenizer):
    """Tokenizes a list of texts and flattens them into a single list of tokens."""
    all_tokens = []
    for text in texts:
        # Check if it's Moses or XLM-R to use correct method
        if hasattr(tokenizer, 'tokenize'):
            tokens = tokenizer.tokenize(text, return_str=False)
            all_tokens.extend(tokens)
    return all_tokens


# --- 2. LANGUAGE MODEL CLASS ---

class TrigramLM:
    def __init__(self, tokens):
        self.total_tokens = len(tokens)
        self.vocab = set(tokens)
        self.vocab_size = len(self.vocab)

        # Counts
        self.unigram_counts = Counter(tokens)
        self.bigram_counts = Counter(get_ngrams(tokens, 2))
        self.trigram_counts = Counter(get_ngrams(tokens, 3))

    def uniform_prob(self):
        return 1.0 / self.vocab_size

    def unigram_prob(self, w):
        if w not in self.vocab: return 0.0
        return self.unigram_counts[w] / self.total_tokens

    def bigram_prob(self, w_prev, w):
        # OOV History Case: If history (w_prev) is unknown, fallback to Uniform
        if w_prev not in self.vocab:
            return self.uniform_prob()

        # Standard Case
        count_bigram = self.bigram_counts[(w_prev, w)]
        count_history = self.unigram_counts[w_prev]

        if count_history == 0: return 0.0
        return count_bigram / count_history

    def trigram_prob(self, w_prev2, w_prev1, w):
        # OOV History Case: If history (w_prev2, w_prev1) is unknown, fallback to Uniform
        if (w_prev2, w_prev1) not in self.bigram_counts:
            return self.uniform_prob()

        # Standard Case
        count_trigram = self.trigram_counts[(w_prev2, w_prev1, w)]
        count_history = self.bigram_counts[(w_prev2, w_prev1)]

        if count_history == 0: return 0.0
        return count_trigram / count_history

    def smoothed_prob(self, w_prev2, w_prev1, w, lambdas):
        l0, l1, l2, l3 = lambdas
        p0 = self.uniform_prob()
        p1 = self.unigram_prob(w)
        p2 = self.bigram_prob(w_prev1, w)
        p3 = self.trigram_prob(w_prev2, w_prev1, w)

        return l0 * p0 + l1 * p1 + l2 * p2 + l3 * p3


# --- 3. EM ALGORITHM & ENTROPY ---

def calculate_cross_entropy(lm, tokens, lambdas):
    log_prob_sum = 0.0
    N = 0
    # Iterate through tokens (skipping first 2 to have history)
    for i in range(2, len(tokens)):
        w_prev2, w_prev1, w = tokens[i - 2], tokens[i - 1], tokens[i]
        p_smooth = lm.smoothed_prob(w_prev2, w_prev1, w, lambdas)

        if p_smooth > 0:
            log_prob_sum -= math.log2(p_smooth)
            N += 1

    return log_prob_sum / N if N > 0 else float('inf')


def run_em_algorithm(lm, heldout_tokens, max_iter=20, tolerance=1e-5):
    # Initialize uniform lambdas
    lambdas = np.array([0.25, 0.25, 0.25, 0.25])
    prev_ce = float('inf')

    print(f"  Starting EM (Initial CE: {calculate_cross_entropy(lm, heldout_tokens, lambdas):.4f})...")

    for it in range(max_iter):
        expected_counts = np.zeros(4)

        # E-Step
        for i in range(2, len(heldout_tokens)):
            w_prev2, w_prev1, w = heldout_tokens[i - 2], heldout_tokens[i - 1], heldout_tokens[i]

            p0 = lm.uniform_prob()
            p1 = lm.unigram_prob(w)
            p2 = lm.bigram_prob(w_prev1, w)
            p3 = lm.trigram_prob(w_prev2, w_prev1, w)

            p_smooth = lambdas[0] * p0 + lambdas[1] * p1 + lambdas[2] * p2 + lambdas[3] * p3

            if p_smooth > 0:
                expected_counts[0] += lambdas[0] * p0 / p_smooth
                expected_counts[1] += lambdas[1] * p1 / p_smooth
                expected_counts[2] += lambdas[2] * p2 / p_smooth
                expected_counts[3] += lambdas[3] * p3 / p_smooth

        # M-Step: Normalize
        lambdas = expected_counts / expected_counts.sum()

        # Check convergence
        ce = calculate_cross_entropy(lm, heldout_tokens, lambdas)
        if abs(prev_ce - ce) < tolerance:
            break
        prev_ce = ce

    print(f"  Converged after {it + 1} iterations.")
    return lambdas


